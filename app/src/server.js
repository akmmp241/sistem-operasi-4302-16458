import { SQL } from "bun";
import { randomBytes, createHash } from "node:crypto";

if (!process.env.DATABASE_URL) {
  throw new Error("DATABASE_URL belum diatur. Salin .env.example menjadi .env terlebih dahulu.");
}
const db = new SQL(process.env.DATABASE_URL);
await db`CREATE TABLE IF NOT EXISTS todos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  completed BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)`;

await db`CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)`;
await db`ALTER TABLE todos ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(id)`;
await db`CREATE INDEX IF NOT EXISTS todos_user_id_idx ON todos(user_id)`;
await db`CREATE TABLE IF NOT EXISTS sessions (
  token_hash CHAR(64) PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL
)`;
await db`DELETE FROM sessions WHERE expires_at <= CURRENT_TIMESTAMP`;

const json = (data, status = 200, headers = {}) => Response.json(data, {
  status, headers: { "Cache-Control": "no-store", ...headers },
});
const sessionAge = 7 * 24 * 60 * 60;
const tokenHash = (token) => createHash("sha256").update(token).digest("hex");
function sessionToken(request) {
  return request.headers.get("cookie")?.split(";").map((part) => part.trim()).find((part) => part.startsWith("rapi_session="))?.slice(13) || "";
}
function sessionCookie(request, token, age = sessionAge) {
  return `rapi_session=${token}; Path=/; HttpOnly; SameSite=Lax; Max-Age=${age}${new URL(request.url).protocol === "https:" ? "; Secure" : ""}`;
}
async function currentUser(request) {
  const token = sessionToken(request);
  if (!/^[a-f0-9]{64}$/.test(token)) return null;
  const [user] = await db`SELECT users.id, users.name, users.email FROM sessions
    JOIN users ON users.id = sessions.user_id
    WHERE token_hash = ${tokenHash(token)} AND expires_at > CURRENT_TIMESTAMP`;
  return user || null;
}
async function signIn(request, user, status = 200) {
  const token = randomBytes(32).toString("hex");
  await db.begin(async (tx) => {
    await tx`DELETE FROM sessions WHERE token_hash = ${tokenHash(sessionToken(request))} OR expires_at <= CURRENT_TIMESTAMP`;
    await tx`INSERT INTO sessions (token_hash, user_id, expires_at)
      VALUES (${tokenHash(token)}, ${user.id}, ${new Date(Date.now() + sessionAge * 1000)})`;
  });
  return json({ user: { id: user.id, name: user.name, email: user.email } }, status, { "Set-Cookie": sessionCookie(request, token) });
}
function credentialsOf(body) {
  const email = typeof body.email === "string" ? body.email.trim().toLowerCase() : "";
  if (email.length > 254 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) throw new InputError("Email tidak valid.");
  if (typeof body.password !== "string" || body.password.length < 8 || body.password.length > 128) {
    throw new InputError("Password harus terdiri dari 8–128 karakter.");
  }
  return { email, password: body.password };
}
const serialize = (row) => ({ ...row, completed: Boolean(row.completed) });
const assets = {
  "/": new URL("../public/index.html", import.meta.url),
  "/style.css": new URL("../public/style.css", import.meta.url),
  "/app.js": new URL("../public/app.js", import.meta.url),
};

class InputError extends Error {}
async function bodyOf(request) {
  if (Number(request.headers.get("content-length")) > 4096) throw new InputError("Data terlalu besar.");
  try {
    const body = await request.json();
    if (!body || Array.isArray(body) || typeof body !== "object") throw new Error();
    return body;
  } catch {
    throw new InputError("Body harus berupa objek JSON yang valid.");
  }
}
function titleOf(value) {
  if (typeof value !== "string" || !value.trim() || [...value.trim()].length > 255) {
    throw new InputError("Nama tugas wajib diisi, maksimal 255 karakter.");
  }
  return value.trim();
}

const server = Bun.serve({
  hostname: process.env.HOST || "127.0.0.1",
  port: Number(process.env.PORT || 3000),
  maxRequestBodySize: 4096,
  async fetch(request) {
    const { pathname } = new URL(request.url);
    const method = request.method;
    try {
      if (assets[pathname]) {
        if (method !== "GET" && method !== "HEAD") return json({ error: "Metode tidak didukung." }, 405);
        return new Response(method === "HEAD" ? null : Bun.file(assets[pathname]), {
          headers: { "Content-Type": pathname.endsWith(".css") ? "text/css" : pathname.endsWith(".js") ? "text/javascript" : "text/html; charset=utf-8" },
        });
      }
      if (pathname === "/api/health" && method === "GET") {
        await db`SELECT 1`;
        return json({ status: "ok", database: "postgres" });
      }
      if (pathname.startsWith("/api/") && !["GET", "HEAD"].includes(method)) {
        const origin = request.headers.get("origin");
        if ((origin && origin !== new URL(request.url).origin) || request.headers.get("sec-fetch-site") === "cross-site") {
          return json({ error: "Permintaan dari situs lain tidak diizinkan." }, 403);
        }
      }
      if (pathname === "/api/auth/register" && method === "POST") {
        const body = await bodyOf(request);
        const { email, password } = credentialsOf(body);
        const name = typeof body.name === "string" ? body.name.trim() : "";
        if (!name || [...name].length > 100) throw new InputError("Nama wajib diisi, maksimal 100 karakter.");
        const hash = await Bun.password.hash(password, { algorithm: "argon2id" });
        const [user] = await db`INSERT INTO users (name, email, password_hash) VALUES (${name}, ${email}, ${hash})
          ON CONFLICT (email) DO NOTHING RETURNING id, name, email`;
        if (!user) return json({ error: "Email sudah terdaftar. Silakan masuk." }, 409);
        return await signIn(request, user, 201);
      }
      if (pathname === "/api/auth/login" && method === "POST") {
        const { email, password } = credentialsOf(await bodyOf(request));
        const [user] = await db`SELECT * FROM users WHERE email = ${email}`;
        if (!user || !await Bun.password.verify(password, user.password_hash)) {
          return json({ error: "Email atau password salah." }, 401);
        }
        return await signIn(request, user);
      }
      if (pathname === "/api/auth/logout" && method === "POST") {
        await db`DELETE FROM sessions WHERE token_hash = ${tokenHash(sessionToken(request))}`;
        return json({ message: "Berhasil keluar." }, 200, { "Set-Cookie": sessionCookie(request, "", 0) });
      }
      if (pathname === "/api/auth/me" && method === "GET") {
        const user = await currentUser(request);
        return user ? json({ user }) : json({ error: "Silakan masuk terlebih dahulu." }, 401);
      }
      const user = pathname.startsWith("/api/todos") ? await currentUser(request) : null;
      if (pathname.startsWith("/api/todos") && !user) return json({ error: "Silakan masuk terlebih dahulu." }, 401);
      if (pathname === "/api/todos") {
        if (method === "GET") {
          return json((await db`SELECT * FROM todos WHERE user_id = ${user.id} ORDER BY created_at DESC, id DESC`).map(serialize));
        }
        if (method === "POST") {
          const title = titleOf((await bodyOf(request)).title);
          const [todo] = await db`INSERT INTO todos (title, user_id) VALUES (${title}, ${user.id}) RETURNING *`;
          return json(serialize(todo), 201);
        }
        return json({ error: "Metode tidak didukung." }, 405);
      }
      const match = pathname.match(/^\/api\/todos\/(\d+)$/);
      if (match) {
        const id = Number(match[1]);
        if (!Number.isSafeInteger(id) || id < 1 || id > 2147483647) return json({ error: "ID tidak valid." }, 400);
        if (method === "PATCH") {
          const body = await bodyOf(request);
          const hasTitle = Object.hasOwn(body, "title");
          const hasCompleted = Object.hasOwn(body, "completed");
          if (!hasTitle && !hasCompleted) throw new InputError("Isi title atau completed untuk memperbarui tugas.");
          const title = hasTitle ? titleOf(body.title) : null;
          if (hasCompleted && typeof body.completed !== "boolean") throw new InputError("completed harus berupa boolean.");
          const [todo] = await db`UPDATE todos SET title = COALESCE(${title}, title), completed = COALESCE(${hasCompleted ? body.completed : null}, completed) WHERE id = ${id} AND user_id = ${user.id} RETURNING *`;
          return todo ? json(serialize(todo)) : json({ error: "Tugas tidak ditemukan." }, 404);
        }
        if (method === "DELETE") {
          const [todo] = await db`DELETE FROM todos WHERE id = ${id} AND user_id = ${user.id} RETURNING id`;
          return todo ? new Response(null, { status: 204 }) : json({ error: "Tugas tidak ditemukan." }, 404);
        }
        return json({ error: "Metode tidak didukung." }, 405);
      }
      return json({ error: "Halaman tidak ditemukan." }, 404);
    } catch (error) {
      if (error instanceof InputError) return json({ error: error.message }, 400);
      console.error(error);
      return json({ error: "Terjadi kesalahan server. Silakan coba lagi." }, 500);
    }
  },
});
console.log(`Todolist berjalan di ${server.url}`);
for (const signal of ["SIGINT", "SIGTERM"]) {
  process.on(signal, async () => {
    await server.stop(true);
    await db.close();
    process.exit(0);
  });
}
