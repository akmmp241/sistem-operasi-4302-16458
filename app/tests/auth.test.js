import { afterAll, beforeAll, expect, test } from "bun:test";
import { SQL } from "bun";

const admin = new SQL(process.env.DATABASE_URL);
const databaseName = `rapi_auth_test_${process.pid}_${Date.now()}`;
let database;
let server;
let base;
let firstCookie;
let secondCookie;
let todoId;
let created = false;
const account = { name: "Pengguna Uji", email: "first@example.test", password: "password-uji-123" };

async function api(path, { cookie, method = "GET", body, origin } = {}) {
  const response = await fetch(`${base}${path}`, {
    method,
    headers: { ...(cookie ? { Cookie: cookie } : {}), ...(body ? { "Content-Type": "application/json" } : {}), ...(origin ? { Origin: origin } : {}) },
    body: body ? JSON.stringify(body) : undefined,
  });
  return { status: response.status, body: response.status === 204 ? null : await response.json(), cookie: response.headers.get("set-cookie") };
}

beforeAll(async () => {
  await admin.unsafe(`CREATE DATABASE "${databaseName}"`);
  created = true;
  const url = new URL(process.env.DATABASE_URL);
  url.pathname = `/${databaseName}`;
  database = new SQL(url.toString());
  // Simulate an existing installation with a shared task.
  await database`CREATE TABLE todos (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(255) NOT NULL, completed BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)`;
  await database`INSERT INTO todos (title) VALUES ('Tugas lama')`;
  server = Bun.spawn([process.execPath, "src/server.js"], {
    cwd: new URL("..", import.meta.url).pathname,
    env: { ...process.env, DATABASE_URL: url.toString(), HOST: "127.0.0.1", PORT: "0" },
    stdout: "pipe", stderr: "inherit",
  });
  const reader = server.stdout.getReader();
  let output = "";
  while (!base) {
    const { value, done } = await reader.read();
    if (done) throw new Error(`Server gagal dimulai: ${output}`);
    output += new TextDecoder().decode(value);
    base = output.match(/http:\/\/[^\s]+/)?.[0];
  }
  reader.releaseLock();
}, 15000);

afterAll(async () => {
  if (server) { server.kill(); await server.exited; }
  if (database) await database.close();
  if (created) await admin.unsafe(`DROP DATABASE "${databaseName}" WITH (FORCE)`);
  await admin.close();
});

test("todos require login and registration validates inputs", async () => {
  expect((await api("/api/todos")).status).toBe(401);
  expect((await api("/api/todos", { method: "POST", body: { title: "test" } })).status).toBe(401);
  expect((await api("/api/auth/register", { method: "POST", body: { ...account, password: "short" } })).status).toBe(400);
  expect((await api("/api/auth/register", { method: "POST", body: { ...account, email: "invalid" } })).status).toBe(400);
  expect((await api("/api/auth/register", { method: "POST", body: { ...account, name: " " } })).status).toBe(400);
});

test("register logs in, hashes password, and rejects duplicate normalized email", async () => {
  const result = await api("/api/auth/register", { method: "POST", body: { ...account, email: " FIRST@example.test " } });
  expect(result.status).toBe(201);
  expect(result.body.user.email).toBe(account.email);
  expect(result.body.user.password_hash).toBeUndefined();
  expect(result.cookie).toContain("HttpOnly");
  expect(result.cookie).toContain("SameSite=Lax");
  firstCookie = result.cookie.split(";")[0];
  const [user] = await database`SELECT password_hash FROM users WHERE email = ${account.email}`;
  expect(user.password_hash).toStartWith("$argon2id$");
  expect(await Bun.password.verify(account.password, user.password_hash)).toBe(true);
  expect((await api("/api/auth/register", { method: "POST", body: account })).status).toBe(409);
  expect((await api("/api/auth/me", { cookie: firstCookie })).body.user.name).toBe(account.name);
  expect((await api("/api/todos", { cookie: firstCookie })).body).toEqual([]);
  expect((await database`SELECT * FROM todos WHERE user_id IS NULL`).length).toBe(1);
});

test("task CRUD is restricted to the owner", async () => {
  const task = await api("/api/todos", { cookie: firstCookie, method: "POST", body: { title: "Tugas pribadi" } });
  expect(task.status).toBe(201);
  todoId = task.body.id;
  const second = await api("/api/auth/register", { method: "POST", body: { ...account, email: "second@example.test" } });
  secondCookie = second.cookie.split(";")[0];
  expect((await api("/api/todos", { cookie: secondCookie })).body).toEqual([]);
  expect((await api(`/api/todos/${todoId}`, { cookie: secondCookie, method: "PATCH", body: { completed: true } })).status).toBe(404);
  expect((await api(`/api/todos/${todoId}`, { cookie: secondCookie, method: "DELETE" })).status).toBe(404);
  const edited = await api(`/api/todos/${todoId}`, { cookie: firstCookie, method: "PATCH", body: { title: "Diperbarui", completed: true } });
  expect(edited.body.completed).toBe(true);
  expect(edited.body.title).toBe("Diperbarui");
});

test("login rejects wrong passwords, rotates sessions, and logout revokes session", async () => {
  expect((await api("/api/auth/login", { method: "POST", body: { ...account, password: "wrong-password" } })).status).toBe(401);
  const login = await api("/api/auth/login", { method: "POST", cookie: firstCookie, body: account });
  expect(login.status).toBe(200);
  expect((await api("/api/auth/me", { cookie: firstCookie })).status).toBe(401);
  firstCookie = login.cookie.split(";")[0];
  expect((await api("/api/todos", { cookie: firstCookie })).body.length).toBe(1);
  expect((await api(`/api/todos/${todoId}`, { cookie: firstCookie, method: "DELETE" })).status).toBe(204);
  const logout = await api("/api/auth/logout", { method: "POST", cookie: firstCookie });
  expect(logout.cookie).toContain("Max-Age=0");
  expect((await api("/api/auth/me", { cookie: firstCookie })).status).toBe(401);
  expect((await api("/api/todos", { cookie: firstCookie })).status).toBe(401);
});

test("expired sessions and cross-site writes are rejected", async () => {
  expect((await api("/api/auth/logout", { method: "POST", cookie: secondCookie, origin: "https://other.example" })).status).toBe(403);
  expect((await api("/api/auth/register", { method: "POST", body: account, origin: "https://other.example" })).status).toBe(403);
  await database`UPDATE sessions SET expires_at = CURRENT_TIMESTAMP - INTERVAL '1 second'`;
  expect((await api("/api/auth/me", { cookie: secondCookie })).status).toBe(401);
});
